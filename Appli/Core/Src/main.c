static uint32_t psram_test(void)
{
  volatile uint32_t *p = (volatile uint32_t *)PSRAM_BASE;
  uint32_t words = PSRAM_TEST_SIZE / 4;
  uint32_t errors = 0;

  for (uint32_t i = 0; i < words; i++)
  {
    p[i] = (uint32_t)&p[i] ^ 0xA5A5A5A5u;
  }

  /* Yazilanlar D-cache'te: PSRAM'e indir ve kopyalari sil, okumalar PSRAM'den gelsin */
  SCB_CleanInvalidateDCache_by_Addr(p, PSRAM_TEST_SIZE);

  for (uint32_t i = 0; i < words; i++)
  {
    uint32_t expected = (uint32_t)&p[i] ^ 0xA5A5A5A5u;
    uint32_t got = p[i];
    if (got != expected)
    {
      if (errors == 0)
      {
        printf("PSRAM ilk hata @ %p: beklenen 0x%08lX, okunan 0x%08lX\r\n",
               (void *)&p[i], expected, got);
      }
      errors++;
    }
  }

  /* Son kelime: 32 MB'in tamamina ulasilabildigini gosterir */
  volatile uint32_t *last = (volatile uint32_t *)(PSRAM_BASE + PSRAM_SIZE - 4);
  *last = 0x12345678u;
  SCB_CleanInvalidateDCache_by_Addr(last, 4);
  if (*last != 0x12345678u)
  {
    errors++;
  }

  return errors;
}

